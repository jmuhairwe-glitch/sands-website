import { PGlite } from '@electric-sql/pglite';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const db=new PGlite();
await db.exec('create role anon; create role authenticated; create role service_role;');
await db.exec(fs.readFileSync('database/enquiries.sql','utf8'));
const id='a852a510-c12f-4e53-a48a-adc142b3c99f';
await db.exec('set role anon');
await db.query("insert into public.customer_enquiries(id,topic,customer_name,phone,location,details,message) values($1,'Training','TEST enquiry','+256700000000','TEST location','{}','TEST message')",[id]);
await assert.rejects(()=>db.query('select * from public.customer_enquiries'),/permission denied/);
await assert.rejects(()=>db.query("update public.customer_enquiries set status='booked'"),/permission denied/);
await assert.rejects(()=>db.query('delete from public.customer_enquiries'),/permission denied/);
await assert.rejects(()=>db.query('select * from public.enquiry_report_settings'),/permission denied/);
await assert.rejects(()=>db.query("insert into public.customer_enquiries(id,topic,customer_name,phone,location,details,message,is_test) values(gen_random_uuid(),'Training','Fake','+256700000000','TEST','{}','Test',true)"),/permission denied/);
await db.exec('reset role;set role authenticated;');
await assert.rejects(()=>db.query('select * from public.customer_enquiries'),/permission denied/);
await db.exec('reset role');
assert.equal((await db.query('select count(*)::int as n from public.customer_enquiries')).rows[0].n,1);
await db.close();console.log('Passed: submission allowed, public/authenticated reads denied, updates/deletes/settings access and protected column writes denied.');
